const VARIANTS = {};

function fillTemplate(tpl, ctx) {
  return tpl.replace(/\{(\w+)\}/g, (_, k) => (ctx[k] != null ? ctx[k] : ""));
}

function registerVariant(id, options) {
  VARIANTS[id] = options;
}

